import { test, expect, setupSitting, answer, complete, allPositive, openReview, more, downloadJSON, noOverflow } from "./helpers.mjs"

test("a negative sitting is five real answers, private handoff, and three brief results", async ({ page }) => {
  await page.goto("/index.html")
  await page.getByRole("link", { name: "New sitting", exact: true }).click()
  await expect(page.getByRole("button", { name: "Begin sitting" })).toBeDisabled()
  await page.getByRole("radio", { name: "Clinical", exact: true }).click()
  await page.getByRole("button", { name: "Begin sitting" }).click()
  await expect(page.locator("#continue")).toHaveCount(0)
  await expect(page.locator(".top-nav")).toHaveCount(0)
  const trace = await complete(page)
  expect(trace.map((row) => row.id)).toEqual(["phq-1", "phq-2", "gad-1", "gad-2", "pcptsd-exposure"])
  await expect(page.locator(".panel-score")).toHaveCount(0)
  await openReview(page)
  await expect(page.locator(".clinical-results .score-graphic")).toHaveCount(3)
  await expect(page.locator('.clinical-results [data-domain="trauma"]')).toContainText("Symptom questions skipped")
  const record = await downloadJSON(page)
  expect(record.symptoms.map((row) => [row.status, row.gateScore, row.total])).toEqual([["gate-closed", 0, null], ["gate-closed", 0, null]])
  expect(record).not.toHaveProperty("responses")
  expect(record).not.toHaveProperty("text")
  expect(record.configuration.policy.id).toBe("open-screen-default")
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length, cookie: document.cookie }))).toEqual({ local: 0, session: 0, cookie: "" })
})

test("all four full branches carry shared items once and agree with downloaded outputs", async ({ page }) => {
  await setupSitting(page, { topics: ["depression", "anxiety", "alcohol", "trauma"], reference: "SYNTHETIC-54" })
  const trace = await complete(page, allPositive)
  expect(trace).toHaveLength(54)
  expect(new Set(trace.map((row) => row.id)).size).toBe(54)
  expect(trace.slice(0, 13).every((row) => row.stage.includes("Stage 1"))).toBe(true)
  expect(trace.slice(13).every((row) => row.stage.includes("Stage 2"))).toBe(true)
  await openReview(page)
  for (const [domain, value, max] of [["depression", 8, 27], ["anxiety", 7, 21], ["alcohol", 3, 40], ["trauma", 20, 80]]) {
    await expect(page.locator(`.clinical-results [data-domain=${domain}] .score-graphic`)).toHaveAttribute("data-value", String(value))
    await expect(page.locator(`.clinical-results [data-domain=${domain}] .score-graphic`)).toHaveAttribute("data-max", String(max))
  }
  await page.getByRole("textbox", { name: "Formulation & follow-up" }).fill("Synthetic findings and agreed next appointment.")
  const record = await downloadJSON(page, { responses: true })
  expect(record.symptoms.map((row) => row.total)).toEqual([8, 7])
  expect(record.alcohol.total).toBe(3)
  expect(record.trauma.pcl.total).toBe(20)
  expect(record.clinician.reference).toBe("SYNTHETIC-54")
  expect(record.clinician.facts).toContain("agreed next appointment")
  expect(Object.keys(record.responses)).toHaveLength(54)
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await noOverflow(page)
  }
})

test("safety actions remain separated across screen sizes and enlarged text", async ({ page }, testInfo) => {
  await setupSitting(page, { topics: ["depression"] })
  await complete(page, (id) => id === "phq-1" ? 2 : id === "phq-9" ? 1 : 0)
  const link = page.getByRole("link", { name: "Official C-SSRS resources ↗", exact: true })
  const button = page.getByRole("button", { name: "Clinician: reviewed; continue under supervision", exact: true })
  for (const [width, font] of [[1440, "100%"], [1061, "100%"], [768, "100%"], [390, "100%"], [320, "100%"], [320, "200%"]]) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate((size) => { document.documentElement.style.fontSize = size }, font)
    const resource = await link.boundingBox()
    const action = await button.boundingBox()
    expect(action.y - (resource.y + resource.height), `Separate safety actions at ${width}px / ${font}`).toBeGreaterThanOrEqual(15.9)
    await noOverflow(page)
  }
  await page.evaluate(() => { document.documentElement.style.fontSize = "100%" })
  await page.setViewportSize({ width: 1061, height: 900 })
  await page.screenshot({ path: testInfo.outputPath("safety-actions.png"), fullPage: true })
  await link.focus()
  await page.keyboard.press("Tab")
  await expect(button).toBeFocused()
  await page.keyboard.press("Enter")
  await complete(page)
  await openReview(page)
  await expect(page.locator(".safety-banner")).toBeVisible()
})

test("safety interruption survives editing a gate closed in forensic context", async ({ page }) => {
  await setupSitting(page, { topics: ["depression"], context: "Forensic" })
  await complete(page, (id) => id === "phq-1" ? 2 : id === "phq-9" ? 1 : 0)
  await expect(page.getByRole("heading", { name: "Let’s check in with your psychologist." })).toBeVisible()
  await expect(page.locator("#open-record")).toHaveCount(0)
  await page.getByRole("button", { name: "Clinician: reviewed; continue under supervision" }).click()
  await complete(page)
  await openReview(page)
  await expect(page.locator(".safety-banner")).toBeVisible()
  await more(page)
  await page.getByRole("button", { name: "Review responses", exact: true }).click()
  await expect(page.getByRole("radio").nth(2)).toHaveAttribute("aria-checked", "true")
  await answer(page, 0)
  await answer(page, 0)
  await openReview(page)
  await expect(page.locator(".safety-banner")).toBeVisible()
  await expect(page.locator('.clinical-results [data-domain="depression"] .panel-score')).toContainText("PHQ-2")
  const record = await downloadJSON(page, { responses: true })
  expect(record.safetyFlag).toBe(true)
  expect(record.symptoms[0].total).toBeNull()
  expect(record.responses["phq-9"]).toBe(1)
  expect(record.text).toContain("Retained safety observation")
  expect(record.forensic).toBe(true)
})

