test("answer activation advances once and repeated input does not skip a question", async ({ page }, testInfo) => {
  await setupSitting(page, { topics: ["depression"] })
  if (testInfo.project.use.hasTouch) {
    await page.getByRole("radio").first().tap()
    await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-2")
    await page.getByRole("button", { name: "Back", exact: true }).click()
  }
  await page.getByRole("radio").first().dblclick()
  await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-2")
  await expect(page.locator("#question-title")).toBeFocused()
  await page.keyboard.down("3")
  await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-3")
  await page.keyboard.down("3")
  await page.keyboard.up("3")
  await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-3")
  await page.getByRole("radio").first().focus()
  await page.keyboard.press("Enter")
  await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-4")
  await page.getByRole("radio").first().focus()
  await page.keyboard.press("Space")
  await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-5")
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await expect(page.getByRole("radio").first()).toHaveAttribute("aria-checked", "true")
  await page.getByRole("radio").first().click()
  await expect(page.locator("#main")).toHaveAttribute("data-step", "phq-5")
})

test("new sitting clears patient details and overrides while requiring a fresh alcohol threshold", async ({ page }) => {
  await setupSitting(page, { topics: ["alcohol"], alcoholThreshold: 4, reference: "SYNTHETIC-PREVIOUS" })
  await complete(page)
  await openReview(page)
  await page.getByRole("textbox", { name: "Formulation & follow-up" }).fill("Previous synthetic patient note")
  await page.getByRole("radio", { name: "Follow-up required", exact: true }).click()
  await more(page)
  page.once("dialog", (dialog) => dialog.accept())
  await page.getByRole("button", { name: "New sitting", exact: true }).click()
  await expect(page.getByRole("textbox", { name: "Reference (optional)" })).toHaveValue("")
  await expect(page.locator('[data-focus-key="alcohol"]')).toHaveAttribute("aria-pressed", "true")
  await expect(page.getByRole("button", { name: "Begin sitting" })).toBeDisabled()
  await expect(page.locator('[aria-label="AUDIT-C threshold"] [aria-checked=true]')).toHaveCount(0)
  await page.getByRole("radio", { name: "≥3", exact: true }).click()
  await page.getByRole("button", { name: "Begin sitting" }).click()
  await complete(page)
  await openReview(page)
  const record = await downloadJSON(page, { responses: true })
  expect(record.clinician.reference).toBe("")
  expect(record.clinician.facts).toBe("")
  expect(record.clinician.safetyReview).toBeNull()
  expect(record.setup.followUps).toEqual({})
  expect(Object.keys(record.responses)).toHaveLength(3)
})

test("optional stress and response-pattern modules produce separate complete outputs", async ({ page }) => {
  await setupSitting(page, { topics: ["validity", "irritability"] })
  const trace = await complete(page, (id) => {
    if (id.startsWith("dass-")) return 1
    const index = Number(id.split("-")[1])
    return index >= (id.startsWith("im-") ? 11 : 6) ? 1 : 3
  })
  expect(trace).toHaveLength(37)
  await openReview(page)
  const record = await downloadJSON(page)
  expect(record.stress).toMatchObject({ raw: 7, doubled: 14 })
  expect(record.validity).toMatchObject({ status: "scored", positiveImpression: true, selfDeception: true })
  expect(record.symptoms).toEqual([])
})

