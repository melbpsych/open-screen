import AxeBuilder from '@axe-core/playwright'
import { test, expect, setupSitting, noOverflow } from './helpers.mjs'

test('workspace navigation names its destinations and current page at enlarged phone width', async ({ page }) => {
  for (const [path, current] of [['/logic.html', 'Logic'], ['/help.html', 'Help'], ['/interview.html', 'Assessment']]) {
    await page.goto(path)
    const nav = page.getByRole('navigation', { name: 'Main navigation' })
    await expect(nav.getByRole('link')).toHaveText(['Home', 'Assessment', 'Logic', /Help/])
    await expect(nav.locator('[aria-current=page]')).toHaveText(current)
    await page.setViewportSize({ width: 320, height: 700 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    await noOverflow(page)
    await nav.getByRole('link', { name: 'Logic', exact: true }).focus()
    await expect(nav.getByRole('link', { name: 'Logic', exact: true })).toBeFocused()
  }
  await page.goto('/index.html#/personality-5')
  await expect(page.getByRole('navigation').locator('[aria-current]')).toHaveCount(0)
})

test('recovery and save validation names the field, focuses it and clears after correction', async ({ page }) => {
  await page.goto('/interview.html?resume=1')
  await page.getByRole('button', { name: 'Unlock file', exact: true }).click()
  const file = page.getByLabel('Encrypted assessment file', { exact: true })
  await expect(file).toBeFocused()
  await expect(file).toHaveAttribute('aria-invalid', 'true')
  await expect(file).toHaveAccessibleDescription(/.+/)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Save encrypted assessment', exact: true }).click()
  await page.getByLabel('Passphrase (12+ characters)', { exact: true }).fill('Synthetic component passphrase')
  const confirm = page.getByLabel('Confirm passphrase', { exact: true })
  await confirm.fill('A different synthetic phrase')
  await page.getByRole('button', { name: 'Encrypt & download', exact: true }).click()
  await expect(confirm).toBeFocused()
  await expect(confirm).toHaveAttribute('aria-invalid', 'true')
  await expect(confirm).toHaveAccessibleDescription('The passphrases do not match.')
  for (const width of [1100, 390, 320]) {
    await page.setViewportSize({ width, height: 700 })
    await noOverflow(page)
  }
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await confirm.fill('Synthetic component passphrase')
  await expect(confirm).not.toHaveAttribute('aria-invalid')
  await expect(page.locator('#vault-confirm-error')).toHaveCount(0)
  await confirm.fill('Changed synthetic passphrase')
  await page.getByRole('button', { name: 'Encrypt & download', exact: true }).click()
  await expect(confirm).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Passphrase (12+ characters)', { exact: true }).fill('Changed synthetic passphrase')
  await expect(confirm).not.toHaveAttribute('aria-invalid')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
})

test('threshold errors keep existing hints and revision requirements remain actionable', async ({ page }) => {
  await page.goto('/logic.html')
  await page.getByRole('button', { name: /Edit PHQ-2 follow-up gate/ }).click()
  const gate = page.getByRole('spinbutton', { name: 'PHQ-2 follow-up gate', exact: true })
  await gate.fill('8')
  await expect(gate).toHaveAttribute('aria-invalid', 'true')
  await expect(gate).toHaveAccessibleDescription(/Default 2.*Active 2.*6/)
  await expect(page.locator('[id="preference-depression.gate-error"]')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save draft revision', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Reset field: PHQ-2 follow-up gate', exact: true }).click()
  await expect(gate).toHaveValue('2')
  await expect(gate).not.toHaveAttribute('aria-invalid')
  await expect(page.locator('[id="preference-depression.gate-error"]')).toHaveCount(0)
  await gate.fill('3')
  await expect(gate).not.toHaveAttribute('aria-invalid')
  await expect(gate).toHaveAccessibleDescription(/Default 2.*Active 2/)
  await page.getByLabel('Reason for customisation', { exact: true }).fill('Synthetic component verification')
  await page.getByRole('button', { name: 'Save draft revision', exact: true }).click()
  const name = page.getByLabel('Revision name', { exact: true })
  await expect(name).toBeFocused()
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await name.fill('Synthetic reviewed setting')
  await expect(name).not.toHaveAttribute('aria-invalid')
  await page.getByRole('button', { name: 'Save draft revision', exact: true }).click()
  await expect(page.locator('.revision-history')).toContainText('Synthetic reviewed setting')
})

test('encrypted saving exposes pending work without disabling cancellation', async ({ page }) => {
  // A controlled crypto boundary observes the genuine operation without a sleep.
  await page.addInitScript(() => {
    const derive = crypto.subtle.deriveKey.bind(crypto.subtle)
    crypto.subtle.deriveKey = async (...args) => {
      await new Promise(resolve => { window.releaseSyntheticCrypto = resolve })
      return derive(...args)
    }
  })
  await setupSitting(page, { topics: ['depression'] })
  await page.getByRole('button', { name: 'Save progress', exact: true }).click()
  await page.getByLabel('Passphrase (12+ characters)', { exact: true }).fill('Synthetic pending passphrase')
  await page.getByLabel('Confirm passphrase', { exact: true }).fill('Synthetic pending passphrase')
  await page.getByRole('button', { name: 'Encrypt & download', exact: true }).click()
  await expect(page.locator('dialog form')).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('button', { name: 'Encrypting…', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeEnabled()
  const download = page.waitForEvent('download')
  await expect.poll(() => page.evaluate(() => typeof window.releaseSyntheticCrypto)).toBe('function')
  await page.evaluate(() => window.releaseSyntheticCrypto())
  expect(await (await download).failure()).toBeNull()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
