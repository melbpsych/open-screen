import AxeBuilder from '@axe-core/playwright'
import {test,expect,setupSitting,complete,openReview,recordDetails,downloadJSON,noOverflow} from './helpers.mjs'

async function captureCopy(page) {
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.syntheticNote=text}}}))
 await page.getByRole('button',{name:'Copy summary',exact:true}).click()
 await expect(page.locator('#export-status')).toHaveText('Clinical summary copied.')
 return page.evaluate(()=>window.syntheticNote)
}

test('completed measures copy directly into notes without a documentation form',async({page},testInfo)=>{
 await setupSitting(page,{reference:'SYNTHETIC-NOTES'})
 await complete(page);await openReview(page,{documentation:false})
 await expect(page.locator('.record-details')).toHaveJSProperty('open',false)
 await expect(page.getByLabel('Reviewing clinician',{exact:true})).not.toBeVisible()
 await expect(page.locator('.assessment-lifecycle,.result-plot')).toHaveCount(0)
 await expect(page.locator('.assessment-history')).not.toBeVisible()
 await expect(page.getByRole('button',{name:'Open PHQ-9',exact:true})).toBeVisible()
 await expect(page.locator('[data-section=result-trauma] > summary')).toHaveText(/Not administered.*Exposure not endorsed/)
 expect((await page.locator('[data-section=result-trauma] > summary').innerText()).match(/Not administered/g)).toHaveLength(1)
 for(const width of [1440,390,320]){
  await page.setViewportSize({width,height:844})
  const first=await page.locator('.clinical-results').boundingBox()
  await expect(page.locator('.guided-safety')).toHaveCount(0)
  await noOverflow(page)
 }
 await page.locator('.summary-preview > summary').click()
 await expect(page.locator('#summary-preview-text')).toBeVisible()
 const preview=await page.locator('#summary-preview-text').innerText()
 await page.locator('.summary-preview > summary').click()
 const note=await captureCopy(page)
 expect(note).toBe(preview)
 expect(note).toContain('PHQ-2: 0/6')
 expect(note).toContain('GAD-2: 0/6')
 expect(note).toContain('not administered (exposure not endorsed)')
 expect(note).not.toContain('Safety review: not recorded')
 expect(note).toContain('Draft')
 expect(note).not.toMatch(/Engine:|Policy:|forensic|current-path/)
 expect(note.match(/PHQ-2/g)).toHaveLength(1)
 await expect(page.locator('.record-details')).toHaveJSProperty('open',false)
 await expect(page.locator('#save-state')).toContainText('Changes not saved')
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('heading',{name:'Results',exact:true}).focus()
 await page.screenshot({path:testInfo.outputPath('minimal-results.png'),fullPage:true})
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
 await page.evaluate(()=>document.documentElement.style.fontSize='200%')
 await page.setViewportSize({width:320,height:700});await noOverflow(page)
})

test('an endorsed answer is visible without forcing risk documentation or blocking finalisation',async({page})=>{
 await setupSitting(page,{topics:['depression']})
 await complete(page,id=>id==='phq-1'?2:id==='phq-9'?1:0)
 await openReview(page,{documentation:false})
 await expect(page.locator('.screening-observation')).toBeVisible()
 await expect(page.locator('.record-details')).toHaveJSProperty('open',false)
 const note=await captureCopy(page)
 expect(note).toContain('PHQ-9 item 9')
 expect(note).not.toMatch(/PRIORITY|not recorded|assessment required/)
 await recordDetails(page)
 await expect(page.locator('.risk-notes')).toHaveJSProperty('open',false)
 await page.getByLabel('Reviewing clinician',{exact:true}).fill('Synthetic reviewer')
 await page.getByLabel('I reviewed this screening record.').check()
 await page.getByRole('button',{name:'Finalise record',exact:true}).click()
 await expect(page.locator('.review-reference')).toContainText('Final')
})

test('event references are available with PCL history without adding a normal review form',async({page})=>{
 await setupSitting(page,{topics:['trauma']})
 await complete(page,()=>0);await openReview(page,{documentation:false})
 const anchor=page.getByLabel('PCL event reference for comparisons',{exact:true})
 await expect(anchor).not.toBeVisible()
 await recordDetails(page)
 await page.locator('.assessment-history > summary').click()
 await expect(anchor).toBeVisible()
 await anchor.fill('SYNTHETIC-EVENT-A')
 const r=await downloadJSON(page)
 expect(r.clinician.practice.pclEventId).toBe('SYNTHETIC-EVENT-A')
 expect(r.trauma.pcl.total).toBe(0)
})

test('one optional risk note is sufficient and remains in copies, reports and final records',async({page})=>{
 await setupSitting(page,{topics:['depression']});await complete(page);await openReview(page,{documentation:false})
 await expect(page.getByLabel('Risk notes',{exact:true})).not.toBeVisible()
 await recordDetails(page)
 await page.locator('.risk-notes > summary').click()
 await expect(page.locator('.risk-details')).toHaveJSProperty('open',false)
 await page.getByLabel('Risk notes',{exact:true}).fill('Synthetic optional note written at clinician discretion')
 const note=await captureCopy(page)
 expect(note).toContain('Synthetic optional note written at clinician discretion')
 expect(note).not.toMatch(/not recorded|required before|needs attention/)
 await page.getByLabel('Reviewing clinician',{exact:true}).fill('Synthetic reviewer')
 await page.getByLabel('I reviewed this screening record.').check()
 await page.getByRole('button',{name:'Finalise record',exact:true}).click()
 await expect(page.locator('.review-reference')).toContainText('Final')
 const r=await downloadJSON(page,{responses:true})
 expect(r.clinician.practice.riskNotes).toContain('clinician discretion')
 expect(r.clinician.safetyReview??null).toBe(null)
 await expect(page.locator('#print-record')).toContainText('Synthetic optional note written at clinician discretion')
})
