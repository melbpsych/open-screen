const byId = new Map(references.map((entry) => [entry.id, entry]))

export function referenceById(id) {
  const entry = byId.get(id)
  if (!entry) throw new Error(`Unknown reference ${id}.`)
  return entry
}

export function referenceList(ids) {
  const seen = new Set()
  const ordered = []
  for (const id of ids) {
    if (seen.has(id)) continue
    seen.add(id)
    ordered.push(referenceById(id))
  }
  return ordered
}
