test('expanded review and export remain usable with text spacing in short landscape',async({page})=>{
 await setupSitting(page,{topics:['depression']});await complete(page);await openReview(page);await safety(page)
 await setupView(page, 'Context')
 if (!await page.locator('.practice-context').evaluate(node => node.open)) await page.locator('.practice-context > summary').click()
 await page.locator('.clinical-context > summary').click()
 await page.addStyleTag({content:'*{line-height:1.5!important;letter-spacing:.12em!important;word-spacing:.16em!important}p{margin-bottom:2em!important}'})
 for(const size of [{width:320,height:700},{width:844,height:390},{width:1024,height:768}]){
  await page.setViewportSize(size);await more(page);await noOverflow(page)
  await expect.poll(async()=>{
   const panel=await page.locator('.export-options').boundingBox()
   return panel.x>=0 && panel.y>=0 && panel.x+panel.width<=size.width && panel.y+panel.height<=size.height && (size.width>700 || panel.width>=size.width-40)
  }).toBe(true)
  await page.getByRole('button',{name:'Save structured JSON',exact:true}).focus()
  await expect.poll(async()=>{const b=await page.getByRole('button',{name:'Save structured JSON',exact:true}).boundingBox();return b.y>=0&&b.y+b.height<=size.height}).toBe(true)
  await page.keyboard.press('Escape')
 }
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
})

