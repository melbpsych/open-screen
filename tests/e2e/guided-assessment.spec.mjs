import { workspaceMenu } from './helpers.mjs'
import AxeBuilder from '@axe-core/playwright'
import { test, expect, setupSitting, setupView, answer, complete, openReview, noOverflow } from './helpers.mjs'

test('practice presets retain the patient reference and require fresh permissions',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('open-screen.templates.v1',JSON.stringify(['Practice intake','Second preset','Third preset','Fourth preset'].map(name=>({name,context:'forensic',topics:['depression','alcohol'],mode:'screening'})))))
 await page.goto('/interview.html')
 await page.getByRole('radio',{name:'Clinical',exact:true}).click()
 await page.getByLabel('Reference (optional)',{exact:true}).fill('SYNTHETIC-PRESET')
 await page.locator('[data-focus-key=alcohol]').click()
 const permission=page.getByRole('checkbox',{name:'No fee is charged to complete this questionnaire.'})
 await permission.check()
 await page.getByRole('radio',{name:'≥3',exact:true}).click()
 await page.locator('.preset-picker > summary').click()
 await page.getByRole('button',{name:/Practice intake/}).click()
 await expect(page.getByRole('button',{name:/Practice intake/})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByRole('button',{name:/Custom assessment/})).toHaveAttribute('aria-pressed','false')
 await expect(page.getByLabel('Reference (optional)',{exact:true})).toHaveValue('SYNTHETIC-PRESET')
 await expect(page.locator('.guided-setting')).toContainText('Forensic')
 await expect(permission).not.toBeChecked()
 await expect(page.getByRole('button',{name:'Continue to Ready',exact:true})).toBeDisabled()
 await setupView(page,'Options')
 await page.locator('[data-section=templates] > summary').click()
 await page.getByLabel('Saved preset',{exact:true}).selectOption('3')
 await page.getByRole('button',{name:'Apply preset',exact:true}).click()
 await setupView(page,'Measures')
 if (!await page.locator('.preset-picker').evaluate(node=>node.open)) await page.locator('.preset-picker > summary').click()
 await expect(page.getByRole('button',{name:/Fourth preset/})).toHaveAttribute('aria-pressed','true')
 await page.locator('[data-focus-key=depression]').click()
 await expect(page.getByRole('button',{name:/Custom assessment/})).toHaveAttribute('aria-pressed','true')
 expect(await page.evaluate(()=>localStorage.getItem('open-screen.templates.v1'))).not.toContain('SYNTHETIC-PRESET')
 await page.setViewportSize({width:320,height:800})
 await page.evaluate(()=>document.documentElement.style.fontSize='200%')
 await noOverflow(page)
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
})

test('catalogue search keeps groups accurate and question instructions become quiet after the first item',async({page})=>{
 await page.goto('/interview.html')
 await page.getByRole('radio',{name:'Clinical',exact:true}).click()
 const search=page.getByRole('searchbox',{name:'Find a measure'})
 await search.fill('Mini-IPIP')
 await expect(page.locator('[data-measure-group=Traits]')).toBeVisible()
 await expect(page.locator('[data-measure-group=Screening]')).not.toBeVisible()
 await page.locator('[data-focus-key=mini-ipip]').click()
 await expect(page.locator('[data-measure-group=Screening]')).not.toBeVisible()
 await search.fill('No such synthetic questionnaire')
 await expect(page.getByText('No matching measures.',{exact:true})).toBeVisible()
 await setupSitting(page,{topics:['depression']})
 await expect(page.locator('#answer-help')).toBeVisible()
 await answer(page)
 await expect(page.locator('#answer-help')).toHaveClass(/sr-only/)
 await expect(page.getByRole('radiogroup')).toHaveAccessibleDescription(/Selecting an answer moves to the next question/)
})

test('raw-score previews retain instrument ranges and final saving updates the workflow state',async({page})=>{
 await setupSitting(page,{topics:['depression','anxiety']})
 await complete(page,id=>id==='phq-1'||id==='gad-1'?2:0)
 await openReview(page)
 await page.locator('[data-section=result-depression] > summary').click()
 await expect(page.locator('[data-section=result-depression] .score-graphic')).toHaveAttribute('aria-label',/PHQ-9: 2 of 27/)
 await page.locator('[data-section=result-anxiety] > summary').click()
 await expect(page.locator('[data-section=result-anxiety] .score-graphic')).toHaveAttribute('aria-label',/GAD-7: 2 of 21/)
 await expect(page.locator('.review-reference')).toContainText('Draft')
 await expect(page.getByRole('button',{name:'Save assessment',exact:true})).toHaveCount(0)
 await page.getByLabel('Reviewing clinician',{exact:true}).fill('Synthetic clinician')
 await page.getByLabel('I reviewed this screening record.').check()
 await page.getByRole('button',{name:'Finalise record',exact:true}).click()
 await expect(page.locator('#review-signoff')).toBeFocused()
 await expect(page.locator('.review-reference')).toContainText('Final')
 await page.getByRole('button',{name:'Save assessment',exact:true}).click()
 await page.getByLabel('Passphrase (12+ characters)',{exact:true}).fill('Synthetic guided assessment password')
 await page.getByLabel('Confirm passphrase',{exact:true}).fill('Synthetic guided assessment password')
 const download=page.waitForEvent('download')
 await page.getByRole('button',{name:'Encrypt & download',exact:true}).click()
 expect(await (await download).failure()).toBeNull()
 await expect(page.locator('#save-state')).toContainText('Encrypted snapshot current')
 await page.getByLabel('Formulation & follow-up',{exact:true}).fill('Synthetic edit after finalisation')
 await expect(page.locator('.review-reference')).toContainText('Draft')
 await expect(page.locator('#save-state')).toContainText('Changes not saved')
 await expect(page.getByRole('button',{name:'Save assessment',exact:true})).toHaveCount(0)
 await page.setViewportSize({width:320,height:700})
 await noOverflow(page)
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
})

test('guided Ready step retains selection and reference when returning to Measures',async({page})=>{
 await page.goto('/interview.html')
 await expect(page.getByRole('navigation',{name:'Setup progress'}).getByRole('button',{name:'Setting',exact:true})).toHaveAttribute('aria-current','step')
 await expect(page.getByRole('button',{name:'Start assessment',exact:true})).not.toBeVisible()
 await page.getByRole('radio',{name:'Clinical',exact:true}).click()
 await page.getByLabel('Reference (optional)',{exact:true}).fill('SYNTHETIC-GUIDED')
 await page.locator('[data-focus-key=alcohol]').click()
 const next=page.getByRole('button',{name:'Continue to Ready',exact:true})
 await expect(next).toBeDisabled()
 await page.getByRole('checkbox',{name:'No fee is charged to complete this questionnaire.'}).check()
 await page.getByRole('radio',{name:'≥3',exact:true}).click()
 await next.click()
 await expect(page.getByRole('heading',{name:'Ready to begin',exact:true})).toBeFocused()
 await expect(page.locator('.guided-recap')).toContainText('Alcohol')
 await page.getByRole('button',{name:'Back to measures',exact:true}).click()
 await expect(page.getByLabel('Reference (optional)',{exact:true})).toHaveValue('SYNTHETIC-GUIDED')
 await expect(page.getByRole('checkbox',{name:'No fee is charged to complete this questionnaire.'})).toBeChecked()
 await page.locator('[data-focus-key=alcohol]').click()
 await next.click()
 await expect(page.locator('.guided-recap')).not.toContainText('Alcohol')
 await page.getByRole('button',{name:'Start assessment',exact:true}).click()
 await expect(page.locator('#main')).toHaveAttribute('data-step','phq-1')
 expect(await page.evaluate(()=>localStorage.length+sessionStorage.length)).toBe(0)
})
